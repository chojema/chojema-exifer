// Removes electron-builder leftovers from dist/ after a build, keeping only installers.
// Runs automatically after `npm run dist:*` (see package.json "post" scripts).
// Usage: node scripts/clean-dist.js [dir]
const fs = require('fs');
const path = require('path');

const dir = path.resolve(process.argv[2] || path.join(__dirname, '..', 'dist'));
if (!fs.existsSync(dir)) process.exit(0);

// Kept: installers people install from, for every version (record of releases).
const KEEP = [/\.dmg$/i, /Setup .*\.exe$/i];
// Removed: unpacked app folders, auto-update metadata (the app has no auto-update),
// and build debug output. All of these are regenerated by the next build.
const REMOVE_FILES = [
  /\.blockmap$/i,
  /^builder-debug\.yml$/i,
  /^builder-effective-config\.yaml$/i,
  /^latest(-mac)?\.yml$/i,
  /\.__uninstaller\.exe$/i,
];

const removed = [];
const kept = [];
for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
  const full = path.join(dir, entry.name);
  if (entry.isDirectory()) {
    fs.rmSync(full, { recursive: true, force: true });
    removed.push(`${entry.name}/`);
  } else if (KEEP.some((re) => re.test(entry.name))) {
    kept.push(entry.name);
  } else if (REMOVE_FILES.some((re) => re.test(entry.name))) {
    fs.rmSync(full, { force: true });
    removed.push(entry.name);
  } else {
    // Unknown file: leave it and say so rather than deleting something unexpected.
    kept.push(`${entry.name} (unrecognized, left in place)`);
  }
}

console.log(`clean-dist: removed ${removed.length ? removed.join(', ') : 'nothing'}`);
console.log(`clean-dist: kept ${kept.length ? kept.join(', ') : 'nothing'}`);
